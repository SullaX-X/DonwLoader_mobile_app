package com.example.data

import android.content.Context
import android.webkit.CookieManager
import java.io.File

object WebViewCookieExporter {

    private val DEFAULT_DOMAINS = listOf(
        "https://www.youtube.com",
        "https://m.youtube.com",
        "https://youtube.com",
        "https://accounts.google.com",
        "https://www.google.com",
        "https://vimeo.com",
        "https://www.dailymotion.com",
        "https://m.soundcloud.com",
        "https://soundcloud.com",
        "https://www.instagram.com",
        "https://www.tiktok.com"
    )

    private val YOUTUBE_AUTH_COOKIE_KEYS = setOf(
        "SID",
        "HSID",
        "SSID",
        "APISID",
        "SAPISID",
        "LOGIN_INFO",
        "__Secure-1PSID",
        "__Secure-3PSID",
        "__Secure-1PAPISID",
        "__Secure-3PAPISID"
    )

    /**
     * Exports cookies from Android's WebView CookieManager into a Netscape HTTP Cookie File.
     * Returns the generated File and the count of exported cookies, or null if none exist.
     */
    fun exportFromWebView(
        context: Context,
        targetFile: File = File(context.filesDir, "cookies.txt"),
        extraUrl: String? = null,
        requireAuthenticatedForYoutube: Boolean = false
    ): Pair<File, Int>? {
        val cookieManager = runCatching { CookieManager.getInstance() }.getOrNull() ?: return null
        runCatching { cookieManager.flush() }

        val urlsToQuery = LinkedHashSet<String>().apply {
            addAll(DEFAULT_DOMAINS)
            if (!extraUrl.isNullOrBlank()) add(extraUrl)
        }

        val cookieLines = mutableListOf<String>()
        val seenKeys = HashSet<String>()
        var hasYoutubeAuthCookie = false

        for (domainUrl in urlsToQuery) {
            val rawCookieHeader = runCatching { cookieManager.getCookie(domainUrl) }.getOrNull()
            if (rawCookieHeader.isNullOrBlank()) continue

            val host = runCatching { java.net.URI(domainUrl).host }.getOrNull() ?: continue
            val baseDomain = when {
                host.endsWith("youtube.com") -> ".youtube.com"
                host.endsWith("google.com") -> ".google.com"
                host.startsWith("www.") -> "." + host.removePrefix("www.")
                host.startsWith("m.") -> "." + host.removePrefix("m.")
                else -> ".$host"
            }

            val pairs = rawCookieHeader.split(";")
            for (pair in pairs) {
                val trimmed = pair.trim()
                val eqIdx = trimmed.indexOf('=')
                if (eqIdx <= 0) continue

                val name = trimmed.substring(0, eqIdx).trim()
                val value = trimmed.substring(eqIdx + 1).trim()
                if (name.isEmpty()) continue

                if (baseDomain == ".youtube.com" && name in YOUTUBE_AUTH_COOKIE_KEYS) {
                    hasYoutubeAuthCookie = true
                }

                val dedupKey = "$baseDomain|$name"
                if (seenKeys.add(dedupKey)) {
                    val expiry = (System.currentTimeMillis() / 1000L) + 31_536_000L
                    // Netscape format: domain \t include_subdomains \t path \t secure \t expiry \t name \t value
                    cookieLines.add("$baseDomain\tTRUE\t/\tTRUE\t$expiry\t$name\t$value")
                }
            }
        }

        if (cookieLines.isEmpty()) return null
        if (requireAuthenticatedForYoutube && !hasYoutubeAuthCookie) return null

        return runCatching {
            targetFile.bufferedWriter().use { writer ->
                writer.write("# Netscape HTTP Cookie File\n")
                writer.write("# Generated by Media Downloader Pro from built-in Browser\n\n")
                for (line in cookieLines) {
                    writer.write(line)
                    writer.write("\n")
                }
            }
            Pair(targetFile, cookieLines.size)
        }.getOrNull()
    }
}
